import type { ApiSchema } from './schema.ts';
import { documentedRecords } from './schema.ts';

/** Native execution inventory is separate from CLR model completeness. Never marks unresolved declarations generated. */
export function emitNativeGraphics(schema: ApiSchema) {
  const records = schema.records.filter(
    r => r.inventory && ['global-method', 'graphic', 'graphic-namespace'].includes(r.inventory.category) && r.publicPath.startsWith('echarts.')
  );
  const paths = records.map(r => r.publicPath.slice(8)).filter(p => p !== 'graphic').sort();
  const constructors = paths.filter(p => /^graphic\.[A-Z]/.test(p));

  // Named helpers only for documented globals; every path stays callable through InvokeNativeAsync.
  const documented = documentedRecords(schema);
  const named = new Set(records.filter(documented).map(r => r.publicPath.slice(8)));
  const methods = paths.filter(path => named.has(path)).map(path => {
    const name = path.split('.').map(p => p[0].toUpperCase() + p.slice(1)).join('') + 'NativeAsync';
    return `    /// <summary>Invokes the source-defined ${path} native contract. Arguments follow upstream order; browser objects/functions use explicit bindings. Typed declaration coverage is tracked separately.</summary>\n    public ValueTask<EChartsBrowserResult> ${name}(EChartsValue[] arguments, CancellationToken cancellationToken = default) => InvokeNativeAsync("${path}", arguments, ${constructors.includes(path) ? 'true' : 'false'}, cancellationToken);`;
  });
  return {
    publicApi: methods.map(m => m.slice(m.indexOf('    public '))).join('\n'),
    files: new Map([
      [
        'src/BlazorECharts/JavaScript/native-graphics.generated.ts',
        '// <auto-generated />\nexport const nativePublicPaths: readonly string[] = '
        + JSON.stringify(paths)
        + ';\nexport const graphicConstructors: readonly string[] = '
        + JSON.stringify(constructors)
        + ';\n',
      ],
      [
        'src/BlazorECharts/Runtime/Generated/NativeGraphics.g.cs',
        '// <auto-generated />\nusing BlazorECharts.Values;\nnamespace BlazorECharts.Runtime;\npublic partial class EChartsRuntime\n{\n'
        + methods.join('\n')
        + '\n}\n',
      ],
    ]),
  };
}
