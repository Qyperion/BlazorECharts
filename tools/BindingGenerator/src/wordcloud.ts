import ts from 'typescript';
import { existsSync, readFileSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { removeStaleFiles } from './generated-files.ts';

interface Model {
  declaration?: string;
  coreDeclaration?: string;
  coreDeclarations?: string[];
  properties: Record<string, string>;
}

interface Mapping {
  version: string;
  models: Record<string, Model>;
  unions: Record<string, string[]>;
  callbacks: Record<string, string>;
  supplements: Record<string, { file: string; anchor: string }>;

  /** Model.property → why a member kept for parity with the plugin's own d.ts has no runtime effect. */
  noEffect?: Record<string, string>;
}

interface Source {
  file: string;
  line: number;
  endLine: number;
  sha256: string;
  text: string;
}

const root = 'src/BlazorECharts.WordCloud/';
const hash = (s: string) => createHash('sha256').update(s).digest('hex');
const pascal = (s: string) => s[0].toUpperCase() + s.slice(1);
const header = `// <auto-generated />\n#nullable enable\nusing System.Text.Json;\nusing System.Text.Json.Serialization;\nusing BlazorECharts.Options;\nusing BlazorECharts.Runtime;\nusing BlazorECharts.Serialization;\nusing BlazorECharts.Values;\nnamespace BlazorECharts.WordCloud;\n\n`;

/** WordCloud's small, source-reconciled projection supplements its incomplete npm declarations. */
/** Writes or verifies a WordCloud generation. A file in its Generated directories, or a wordcloud- file of the shared docs/api-coverage,
 * schemas/generated and schemas/upstream, that the generation lacks is stale. */
export async function writeWordCloudGeneration(files: Map<string, string>, base: string, check: boolean): Promise<void> {
  for (const [path, content] of files) {
    const target = join(base, path);
    if (check) {
      let actual: string;
      try {
        actual = await readFile(target, 'utf8');
      } catch {
        throw new Error(`Missing WordCloud generated file: ${path}`);
      }

      if (actual !== content)
        throw new Error(`WordCloud generated drift: ${path}`);
    } else {
      await mkdir(dirname(target), { recursive: true });
      await writeFile(target, content);
    }
  }

  await removeStaleFiles(
    files.keys(),
    base,
    [
      { dir: root + 'Options/Generated/', recursive: true },
      { dir: root + 'Serialization/Generated/', recursive: true },
      ...['docs/api-coverage/', 'schemas/generated/', 'schemas/upstream/'].map(dir => ({ dir, owns: (name: string) => name.startsWith('wordcloud-') })),
    ],
    check
  );
}

export async function generateWordCloud(input?: Mapping) {
  const config: Mapping = input ?? JSON.parse(await readFile('schemas/overrides/wordcloud-3.0.0.json', 'utf8'));

  // omit:<reason> maps a declared member that the series does not read from options; it stays an unknown JSON field.
  const omitted = (s: string) => s.startsWith('omit:');
  for (const [model, definition] of Object.entries(config.models))
    for (const [name, mapping] of Object.entries(definition.properties))
      if (omitted(mapping) && !mapping.slice(5).trim())
        throw new Error(`WordCloud omit mapping ${model}.${name} needs a reason`);

  const noEffect = new Map(Object.entries(config.noEffect ?? {}));
  for (const [key, reason] of noEffect) {
    const [model, name] = key.split('.');
    const mapping = config.models[model]?.properties[name];
    if (!mapping || omitted(mapping) || !reason.trim())
      throw new Error(`WordCloud noEffect ${key} must name a generated member and a reason`);
  }

  // The source spans below must originate in the same verified archives as the product assets.
  execFileSync(process.execPath, ['tools/Assets/acquire-upstream.mjs', '--verify'], { stdio: 'pipe' });
  const paths = [
    'echarts-wordcloud/index.d.ts', 'echarts-wordcloud/README.md', 'echarts-wordcloud/src/WordCloudSeries.js',
    'echarts-wordcloud/src/WordCloudView.js', 'echarts-wordcloud/src/layout.js', 'echarts/types/dist/echarts.d.ts',
    'echarts/lib/model/Series.js', 'echarts/lib/label/labelStyle.js', 'echarts/lib/visual/style.js', 'echarts/lib/component/tooltip/TooltipView.js',
  ];
  const sources = new Map<string, { text: string; ast: ts.SourceFile }>();
  for (const path of paths) {
    const text = await readFile('artifacts/upstream/' + path, 'utf8');
    sources.set(path, { text, ast: ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true) });
  }

  const span = (file: string, node?: ts.Node, anchor?: string): Source => {
    const { text, ast } = sources.get(file)!;
    const start = node?.getStart(ast) ?? text.indexOf(anchor!);
    if (start < 0)
      throw new Error(`Missing WordCloud source anchor ${file}: ${anchor}`);

    const end = node?.getEnd() ?? start + anchor!.length;
    return {
      file,
      line: ast.getLineAndCharacterOfPosition(start).line + 1,
      endLine: ast.getLineAndCharacterOfPosition(end).line + 1,
      sha256: hash(text),
      text: text.slice(start, end),
    };
  };
  const declarations = new Map<string, ts.InterfaceDeclaration | ts.TypeAliasDeclaration>();
  for (const { ast } of sources.values()) {
    const walk = (node: ts.Node) => {
      if (ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node))
        declarations.set(node.name.text, node);

      ts.forEachChild(node, walk);
    };
    walk(ast);
  }

  const properties = (name: string): Map<string, Source> => {
    const decl = declarations.get(name);
    if (!decl)
      throw new Error(`Missing declaration ${name}`);

    const result = new Map<string, Source>();
    for (const clause of ts.isInterfaceDeclaration(decl) ? decl.heritageClauses ?? [] : [])
      for (const type of clause.types) {
        for (const [key, value] of properties(type.expression.getText()))
          result.set(key, value);
      }

    const members = ts.isInterfaceDeclaration(decl) ? decl.members : ts.isTypeLiteralNode(decl.type) ? decl.type.members : [];
    for (const member of members)
      if (ts.isPropertySignature(member) && member.name)
        result.set(member.name.getText().replaceAll("'", ''), span(decl.getSourceFile().fileName, member));

    return result;
  };
  const inherited = properties('SeriesOption');

  // Inventory the actual createTextStyle call path independently of the mapping list.
  // The plugin delegates to these core functions, including fields omitted by its d.ts.
  const runtimeTextProperties = new Map<string, Source>();
  const labelFile = 'echarts/lib/label/labelStyle.js';
  const labelAst = sources.get(labelFile)!.ast;
  const constantStrings = new Map<string, string>();
  const constants = (node: ts.Node) => {
    if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name) && node.initializer) {
      if (ts.isStringLiteral(node.initializer))
        constantStrings.set(node.name.text, node.initializer.text);

      if (node.name.text.startsWith('TEXT_PROPS_') && ts.isArrayLiteralExpression(node.initializer))
        for (const item of node.initializer.elements)
          if (ts.isStringLiteral(item))
            runtimeTextProperties.set(item.text, span(labelFile, item));
    }

    ts.forEachChild(node, constants);
  };
  constants(labelAst);
  const collectTextReads = (node: ts.Node) => {
    if (ts.isCallExpression(node) && ts.isPropertyAccessExpression(node.expression)
      && node.expression.expression.getText(labelAst) === 'textStyleModel'
      && ['get', 'getShallow', 'getModel'].includes(node.expression.name.text)) {
      const arg = node.arguments[0];
      const key = arg && ts.isStringLiteral(arg) ? arg.text : arg && ts.isIdentifier(arg) ? constantStrings.get(arg.text)
        : arg && ts.isArrayLiteralExpression(arg) && ts.isStringLiteral(arg.elements[0]) ? arg.elements[0].text : undefined;
      if (key)
        runtimeTextProperties.set(key, span(labelFile, node));
    }

    ts.forEachChild(node, collectTextReads);
  };
  for (const node of labelAst.statements)
    if (ts.isFunctionDeclaration(node)
      && ['setTextStyleCommon', 'setTokenTextStyle'].includes(node.name?.text ?? ''))
      collectTextReads(node);

  const typeFacts = (node: ts.TypeNode): string[] | undefined => {
    if (node.kind === ts.SyntaxKind.NumberKeyword)
      return ['double'];

    if (node.kind === ts.SyntaxKind.StringKeyword)
      return ['string'];

    if (node.kind === ts.SyntaxKind.BooleanKeyword)
      return ['bool'];

    if (ts.isLiteralTypeNode(node) && ts.isStringLiteral(node.literal))
      return ['literal:' + node.literal.text];

    if (ts.isArrayTypeNode(node))
      return typeFacts(node.elementType)?.map(s => s + '[]');

    if (ts.isUnionTypeNode(node)) {
      const facts = node.types.map(typeFacts);
      return facts.every(Boolean) ? facts.flat() as string[] : undefined;
    }

    if (ts.isTypeReferenceNode(node)) {
      const alias = declarations.get(node.typeName.getText());
      if (alias && ts.isTypeAliasDeclaration(alias))
        return typeFacts(alias.type);
    }

    return undefined;
  };
  const coreUnionFacts = (name: string): string[] => {
    const path = `src/BlazorECharts/Values/Generated/${name}.g.cs`;
    return existsSync(path)
      ? [...readFileSync(path, 'utf8').matchAll(new RegExp(`public static ${name} From\\(([\\w\\[\\]]+) value\\)`, 'g'))].map(m => m[1])
      : ['core:' + name];
  };
  const mappingFacts = (name: string): string[] => config.unions[name] ? config.unions[name].flatMap(mappingFacts)
    : name.startsWith('literal:')
      ? name.slice(8).split(',').map(s => 'literal:' + s)
      : name.startsWith('core:') ? coreUnionFacts(name.slice(5)) : [name];
  const coreText = declarations.get('TextCommonOption') as ts.InterfaceDeclaration;
  for (const member of coreText.members)
    if (ts.isPropertySignature(member) && member.type) {
      const name = member.name.getText();
      const required = typeFacts(member.type);
      const actual = mappingFacts(config.models.WordCloudTextStyle.properties[name] ?? 'missing');
      if (required?.some(s => !actual.includes(s) && !(s.startsWith('literal:') && actual.includes('string'))))
        throw new Error(`WordCloudTextStyle.${name} narrows core source alternatives: ${required.join(' | ')}`);
    }

  const nestedProperty = (container: string, name: string): Source => {
    const decl = declarations.get(container);
    if (!decl)
      throw new Error(`Missing source container ${container}`);

    let found: ts.PropertySignature | undefined;
    const walk = (node: ts.Node) => {
      if (!found && ts.isPropertySignature(node) && node.name.getText() === name)
        found = node;

      if (!found)
        ts.forEachChild(node, walk);
    };
    walk(decl);
    if (!found)
      throw new Error(`Missing source member ${container}.${name}`);

    return span(decl.getSourceFile().fileName, found);
  };
  const records: { id: string; model: string; name: string; mapping: string; source: Source; test: string; status: string; noEffect?: string }[] = [];
  for (const [model, definition] of Object.entries(config.models)) {
    const declared = definition.declaration
      ? properties(definition.declaration)
      : definition.coreDeclaration ? properties(definition.coreDeclaration) : new Map<string, Source>();
    for (const container of definition.coreDeclarations ?? [])
      for (const [key, value] of properties(container))
        if (!declared.has(key))
          declared.set(key, value);

    if (model === 'WordCloudSeriesOption')
      for (const [key, value] of inherited)
        if (!declared.has(key))
          declared.set(key, value);

    if (model === 'WordCloudTextStyle' || model === 'WordCloudItemTextStyle')
      for (const [key, value] of runtimeTextProperties)
        if (!declared.has(key))
          declared.set(key, value);

    for (const key of declared.keys())
      if (!definition.properties[key])
        throw new Error(`Unmapped WordCloud property ${model}.${key}`);

    for (const [name, mapping] of Object.entries(definition.properties)) {
      let source = declared.get(name);
      const supplement = config.supplements[name];
      if (!source && supplement)
        source = span(supplement.file, undefined, supplement.anchor);

      if (!source && model === 'WordCloudState')
        source = nestedProperty('StatesOptionMixin', name);

      if (!source && model === 'WordCloudDataItem')
        source = name === 'select' || name === 'blur' ? nestedProperty('StatesOptionMixin', name) : nestedProperty('OptionDataItemObject', name);

      if (!source && model === 'WordCloudImageBackground')
        source = nestedProperty('WordCloudTextStyle', 'image');

      if (!source)
        throw new Error(`Missing explicit source for ${model}.${name}`);

      records.push({
        id: `wordcloud:${model}.${name}`,
        model,
        name,
        mapping,
        source,
        test: 'WordCloudModelTests.WordCloudModels_CoverEveryInventoryProperty',
        status: omitted(mapping) ? 'omitted' : 'generated',
        ...(noEffect.has(`${model}.${name}`) ? { noEffect: noEffect.get(`${model}.${name}`) } : {}),
      });
    }
  }

  for (const supplement of Object.values(config.supplements))
    span(supplement.file, undefined, supplement.anchor);

  const flat = (s: string): string[] => config.unions[s] ? config.unions[s].flatMap(flat) : [s];

  // A ? suffix before [] marks nullable array elements, as in the core ZRColor?[]?[] palette layers.
  const cs = (s: string): string => s.endsWith('[]')
    ? cs(s.slice(0, -2)) + '[]'
    : s.endsWith('?') ? cs(s.slice(0, -1)) + '?' : s === 'double' ? 'double' : s === 'bool' || s === 'literal:false' ? 'bool'
      : s === 'string' || s.startsWith('literal:') ? 'string' : s === 'native' ? 'EChartsObjectReference'
        : s.startsWith('function:')
          ? `JsFunction<${s.slice(9)}>`
          : s.startsWith('core-many:') ? `${s.slice(10)}OneOrMany` : s.startsWith('core:') || s.startsWith('enum:') ? s.slice(5) : s;

  // core:X is a core model or a core union (read through IReadableOptionValue); core-many:X is XOneOrMany, X or an array of a core union.
  const coreValue = (name: string) => {
    const value = existsSync(`src/BlazorECharts/Values/Generated/${name}.g.cs`);
    if (!value && !existsSync(`src/BlazorECharts/Options/Generated/${name}.cs`))
      throw new Error(`Unknown core type ${name}`);

    return value;
  };
  const matches = (s: string, v: string, depth = 0): string => {
    if (s.endsWith('[]'))
      return `(${v}.ValueKind == JsonValueKind.Array && ${v}.EnumerateArray().All(item${depth} => ${matches(s.slice(0, -2), 'item' + depth, depth + 1)}))`;

    if (s.endsWith('?'))
      return `(${v}.ValueKind == JsonValueKind.Null || ${matches(s.slice(0, -1), v, depth)})`;

    if (s === 'double')
      return `${v}.ValueKind == JsonValueKind.Number`;

    if (s === 'bool')
      return `(${v}.ValueKind is JsonValueKind.True or JsonValueKind.False)`;

    if (s === 'string' || s.startsWith('enum:'))
      return `${v}.ValueKind == JsonValueKind.String`;

    if (s === 'literal:false')
      return `${v}.ValueKind == JsonValueKind.False`;

    if (s.startsWith('literal:'))
      return `(${v}.ValueKind == JsonValueKind.String && (${s.slice(8).split(',').map(x => `${v}.GetString() == ${JSON.stringify(x)}`).join(' || ')}))`;

    if (s === 'native' || s.startsWith('function:'))
      return `${v}.ValueKind == JsonValueKind.Null`;

    if (s.startsWith('core-many:'))
      return `CoreValues.Matches<${cs(s)}>(${v})`;

    if (s.startsWith('core:'))
      return coreValue(s.slice(5)) ? `CoreValues.Matches<${s.slice(5)}>(${v})` : `${v}.ValueKind == JsonValueKind.Object`;

    return config.models[s] ? `WordCloudTypeRegistration.Matches${s}(${v})` : `${s}.Matches(${v})`;
  };
  const read = (s: string, v: string, depth = 0): string =>
    s.endsWith('[]') ? `${v}.EnumerateArray().Select(item${depth} => ${read(s.slice(0, -2), 'item' + depth, depth + 1)}).ToArray()`
      : s.endsWith('?') ? `(${v}.ValueKind == JsonValueKind.Null ? (${cs(s)})null : ${read(s.slice(0, -1), v, depth)})`
        : s === 'double' ? `${v}.GetDouble()` : s === 'bool' || s === 'literal:false' ? `${v}.GetBoolean()`
          : s === 'string' || s.startsWith('literal:') ? `${v}.GetString()!`
            : s === 'native' || s.startsWith('function:') ? 'null'
              : s.startsWith('enum:') ? `(${cs(s)})${v}.GetString()!`
                : s.startsWith('core-many:') ? `CoreValues.Read<${cs(s)}>(${v})`
                  : s.startsWith('core:') ? (coreValue(s.slice(5)) ? `CoreValues.Read<${s.slice(5)}>(${v})` : `context.Read<${s.slice(5)}>(${v})`)
                    : s === 'WordCloudRichText' ? `WordCloudRichText.Read(${v}, context)`
                      : config.models[s] ? `Read${s}(${v}, context)` : `${s}.Read(${v})`;
  const files = new Map<string, string>();
  let registration = header + '/// <summary>Explicit serializers and readers for the optional WordCloud models.</summary>\npublic static class WordCloudTypeRegistration\n{\n    private static readonly Lazy<EChartsSerializationContext> s_readContext = new(() => { var context = OptionMetadata.CreateContext(); Register(context); return context; });\n    internal static EChartsSerializationContext ReadContext => s_readContext.Value;\n    /// <summary>Adds WordCloud metadata to an existing core context.</summary>\n    public static void Register(EChartsSerializationContext context)\n    {\n';
  for (const [name, model] of Object.entries(config.models)) {
    const series = name === 'WordCloudSeriesOption';
    let code = header + `/// <summary>Source-reconciled ${name} for @qyperion/echarts-wordcloud ${config.version}.</summary>\npublic sealed class ${name} : ${series ? 'SeriesOption' : 'OptionObject'}\n{\n`;
    if (series)
      code += `    /// <summary>Creates the exact wordCloud series discriminator.</summary>\n    public ${name}() : base("wordCloud") { }\n`;

    const entries = Object.entries(model.properties).filter(([n, s]) => !omitted(s) && (!series || n !== 'type'));
    for (const [n, s] of entries) {
      let validation = '';
      if (s.startsWith('literal:'))
        validation = `if (value is not null && !(${s.slice(8).split(',').map(x => `value == ${JSON.stringify(x)}`).join(' || ')})) throw new ArgumentException("Invalid ${n} literal.", nameof(value)); `;

      const remarks = noEffect.has(`${name}.${n}`)
        ? `    /// <remarks>No effect in @qyperion/echarts-wordcloud ${config.version}: ${noEffect.get(`${name}.${n}`)!.replaceAll('&', '&amp;').replaceAll('<', '&lt;')}</remarks>\n`
        : '';
      code += `    private ${cs(s)}? _${n};\n    /// <summary>Gets or sets the exact upstream ${n} value, preserving explicit null.</summary>\n${remarks}    public ${cs(s)}? ${pascal(n)} { get => _${n}; set { ${validation}SetProperty(ref _${n}, value, "${n}"); } }\n`;
    }

    files.set(root + `Options/Generated/${name}.g.cs`, code + '}\n');
    registration += `        context.${series ? 'RegisterSeries("wordCloud", ' : 'Register('}new OptionTypeRegistration<${name}>(Write${name}, Read${name}));\n`;
  }

  registration += '    }\n    internal static OptionObject Read(string model, JsonElement json, EChartsSerializationContext context) => model switch\n    {\n';
  for (const name of Object.keys(config.models))
    registration += `        "${name}" => Read${name}(json, context),\n`;

  registration += '        _ => throw new ArgumentException("Unknown WordCloud model.", nameof(model))\n    };\n';
  for (const [name, model] of Object.entries(config.models)) {
    registration += `    internal static bool Matches${name}(JsonElement json) => json.ValueKind == JsonValueKind.Object`;
    for (const [n, s] of Object.entries(model.properties).filter(([, s]) => !omitted(s)))
      registration += ` && (!json.TryGetProperty("${n}", out var p${pascal(n)}) || p${pascal(n)}.ValueKind == JsonValueKind.Null || (${matches(s, 'p' + pascal(n))}))`;

    registration += ';\n';
    registration += `    private static void Write${name}(Utf8JsonWriter writer, ${name} value, EChartsSerializationContext context, string path)\n    {\n`;
    for (const [n] of Object.entries(model.properties).filter(([, s]) => !omitted(s)))
      registration += `        context.WriteProperty(writer, value, "${n}", value.${pascal(n)}, path);\n`;

    registration += `    }\n    internal static ${name} Read${name}(JsonElement json, EChartsSerializationContext context)\n    {\n        if (json.ValueKind != JsonValueKind.Object) throw new JsonException("Expected ${name} object.");\n        var value = new ${name}();\n        foreach (var property in json.EnumerateObject())\n        {\n            var field = property.Value;\n            switch (property.Name)\n            {\n`;
    for (const [n, s] of Object.entries(model.properties).filter(([, s]) => !omitted(s))) {
      if (n === 'type' && name === 'WordCloudSeriesOption') {
        registration += '                case "type": if (field.GetString() != "wordCloud") throw new JsonException("Invalid wordCloud discriminator."); break;\n';
        continue;
      }

      registration += `                case "${n}":\n                    if (field.ValueKind != JsonValueKind.Null && !(${matches(s, 'field')})) throw new JsonException("Invalid ${name}.${n}.");\n                    value.${pascal(n)} = field.ValueKind == JsonValueKind.Null ? (${cs(s)}?)null : ${read(s, 'field')}; break;\n`;
    }

    registration += '                default: value.AdditionalProperties[property.Name] = EChartsValue.FromJson(field); break;\n            }\n        }\n        return value;\n    }\n';
  }

  files.set(
    root + 'Serialization/Generated/WordCloudTypeRegistration.g.cs',
    registration + '}\n\n/// <summary>Reads core unions through their public reader contract.</summary>\ninternal static class CoreValues\n{\n    internal static bool Matches<T>(JsonElement json) where T : struct, IReadableOptionValue<T> => T.Matches(json);\n    internal static T Read<T>(JsonElement json) where T : struct, IReadableOptionValue<T> => T.Read(json);\n}\n'
  );
  for (const [name, alternatives] of Object.entries(config.unions)) {
    const specs = [...new Set(alternatives.flatMap(flat))];
    let code = header + `/// <summary>Exact source alternatives: ${alternatives.join(' | ').replaceAll('<', '&lt;')}.</summary>\npublic readonly struct ${name} : IOptionValue, IJsonOnSerializing\n{\n    private readonly object? _value;\n    private readonly bool _initialized;\n    private ${name}(object? value) { _value = value; _initialized = true; }\n`;
    for (const type of [...new Set(specs.map(cs))]) {
      const literal = specs.filter(s => cs(s) === type && s.startsWith('literal:'));
      const validation = literal.length && !specs.some(s => cs(s) === type && !s.startsWith('literal:'))
        ? `if (!(${literal.flatMap(s => s.slice(8).split(',')).map(x => `value == ${x === 'false' ? 'false' : JSON.stringify(x)}`).join(' || ')})) throw new ArgumentException("Invalid ${name} literal.", nameof(value)); `
        : '';
      code += `    /// <summary>Creates the ${type.replaceAll('<', '&lt;')} alternative.</summary>\n    public static ${name} From(${type} value) { ${validation}return new(value); }\n    /// <summary>Preserves the source alternative.</summary>\n    public static implicit operator ${name}(${type} value) => From(value);\n`;
    }

    code += '    /// <summary>Gets the stored alternative: the value passed to <c>From</c>, or the <see cref="EChartsValue"/> JSON of a value read from a getOption snapshot.</summary>\n    public object? Value => _value;\n';
    for (const type of [...new Set(specs.map(cs))]) {
      const group = specs.filter(s => cs(s) === type);
      const valueType = ['double', 'bool'].includes(type) || !!config.unions[type];
      const reads = group.every(s => s === 'native' || s.startsWith('function:')) ? '' : (() => {
        const expression = read(group[0], 'json').replace(/(?<![.\w])Read(WordCloud\w+)\(/g, 'WordCloudTypeRegistration.Read$1(');
        const context = expression.includes('context') ? '            var context = WordCloudTypeRegistration.ReadContext;\n' : '';
        return `        if (_value is EChartsValue raw && raw.TryGetJson(out var json) && json.ValueKind != JsonValueKind.Null && (${group.map(s => matches(s, 'json')).join(' || ')}))\n        {\n${context}            value = ${expression};\n            return true;\n        }\n`;
      })();
      code += `    /// <summary>Gets the ${type.replaceAll('<', '&lt;')} alternative, also from a value read from JSON.</summary>\n    public bool TryGet(${valueType ? `out ${type} value` : `[System.Diagnostics.CodeAnalysis.NotNullWhen(true)] out ${type}? value`})\n    {\n        if (_value is ${type} typed) { value = typed; return true; }\n${reads}        value = default;\n        return false;\n    }\n`;
    }

    code += `    internal static bool Matches(JsonElement json) => ${specs.map(s => `(${matches(s, 'json')})`).join(' || ')};\n    internal static ${name} Read(JsonElement json)\n    {\n        if (!Matches(json)) throw new JsonException("Invalid ${name}.");\n        return new(EChartsValue.FromJson(json));\n    }\n    void IOptionValue.Write(Utf8JsonWriter writer, EChartsSerializationContext context, string path)\n    {\n        if (!_initialized) throw new OptionSerializationException("Uninitialized ${name}.", path, typeof(${name}));\n        context.WriteValue(writer, _value, path);\n    }\n    void IJsonOnSerializing.OnSerializing() => throw new NotSupportedException("Use OptionSerializer for WordCloud values.");\n}\n`;

    // Object alternatives remain validated JSON on reads, preserving all fields instead of guessing a subtype.
    files.set(root + `Options/Generated/${name}.g.cs`, code);
  }

  for (const [name, signature] of Object.entries(config.callbacks))
    files.set(
      root + `Options/Generated/${name}.g.cs`,
      header + `/// <summary>Browser callback ${signature.replaceAll('=>', 'returns').replaceAll('<', '&lt;')}.</summary>\npublic readonly struct ${name} : IJsFunctionSignature\n{\n    /// <summary>Gets the source contract identity.</summary>\n    public static string Id => "wordcloud:${name}";\n}\n`
    );

  const callbacks = Object.entries(config.callbacks).map(([name, signature]) => ({
    name,
    signature,
    source: name === 'WordCloudShapeSignature' ? span('echarts-wordcloud/src/layout.js', undefined, 'rx = settings.shape((t / T) * 2 * Math.PI);')
      : name === 'WordCloudColorSignature' ? nestedProperty('WordCloudTextStyle', 'color')
        : name === 'WordCloudTransitionDelaySignature' ? nestedProperty('UniversalTransitionOption', 'delay')
          : span('echarts/types/dist/echarts.d.ts', declarations.get(name === 'WordCloudDurationSignature'
            ? 'AnimationDurationCallback'
            : name === 'WordCloudDelaySignature' ? 'AnimationDelayCallback' : 'LabelLayoutOptionCallback')),
    file: root + `Options/Generated/${name}.g.cs`,
    test: 'WordCloudModelTests.WordCloudCallbacks_UseModuleOrExplicitInline / WordCloudUnionAlternatives_PreserveShapesAndRejectWrongJson',
  }));
  const unions = Object.entries(config.unions).map(([name, alternatives]) => ({
    name,
    alternatives,
    sources: records.filter(r => r.mapping === name || r.mapping === name + '[]' || r.mapping === name + '[][]').map(r => r.source),
    file: root + `Options/Generated/${name}.g.cs`,
    test: 'WordCloudModelTests.WordCloudUnionAlternatives_PreserveShapesAndRejectWrongJson / WordCloudNativeImages_UseExistingReferenceBindingsAndPolicy',
  }));
  const runtimeTextInventory = [...runtimeTextProperties].map(
    ([name, source]) => ({ name, source, mapping: config.models.WordCloudTextStyle.properties[name] })
  );
  const inventory = {
    formatVersion: 1,
    version: config.version,
    coreVersion: '6.1.0',
    records,
    callbacks,
    unions,
    runtimeTextInventory,
    supplements: config.supplements,
    unresolved: [],
  };
  files.set(`schemas/upstream/wordcloud-${config.version}.api.json`, JSON.stringify(inventory, null, 2) + '\n');
  files.set(
    `docs/api-coverage/wordcloud-${config.version}.md`,
    `# WordCloud ${config.version} models\n\n${records.length} source-backed properties; no unresolved WordCloud mappings. Registration uses the existing extensible series registry. Layout/export completion uses the stable export participant. Native ZRender paint values also accept an explicit browser reference.\n\n| ID | C# model | Mapping | Exact source | Test |\n|---|---|---|---|---|\n`
    + records.map(r => `| ${r.id} | ${r.model}.${pascal(r.name)} | ${r.mapping.replaceAll('|', '/')}${r.noEffect ? ' (no effect: ' + r.noEffect + ')' : ''} | ${r.source.file}:${r.source.line} (${r.source.sha256.slice(0, 12)}) | ${r.test} |`).join('\n')
    + '\n'
  );
  files.set('schemas/generated/wordcloud-public-api.txt', [
    ...records.filter(r => r.status === 'generated').map(
      r => `BlazorECharts.WordCloud.${r.model}.${pascal(r.name)} : ${cs(r.mapping)}${r.name === 'type' && r.model === 'WordCloudSeriesOption' ? ' { get; }' : '? { get; set; }'}`
    ),
    ...unions.map(u => `${u.name}.From / implicit : ${u.alternatives.flatMap(flat).map(cs).join(' | ')}`),
    ...unions.map(u => `${u.name}.Value / TryGet : ${[...new Set(u.alternatives.flatMap(flat).map(cs))].join(' | ')}`),
    ...callbacks.map(c => `${c.name} : ${c.signature}`),
  ].join('\n') + '\n');
  const manifest = {
    formatVersion: 1,
    records: records.filter(
      r => r.status === 'generated'
    ).map(r => ({
      id: r.id,
      file: root + `Options/Generated/${r.model}.g.cs`,
      symbol: `BlazorECharts.WordCloud.${r.model}.${pascal(r.name)}`,
      source: r.source,
      test: r.test,
    })),
    unions,
    callbacks,
    files: [...files].map(
      ([file, content]) => ({ file, sha256: hash(content) })
    ),
  };
  files.set('schemas/generated/wordcloud-manifest.json', JSON.stringify(manifest, null, 2) + '\n');
  return { files, inventory };
}
